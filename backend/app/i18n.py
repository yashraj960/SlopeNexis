def normalize_language(code: str | None) -> str:
    return code if code in LANGUAGES else "en"

def localized_alert(alert: dict, language: str = "en") -> str:
    language = normalize_language(language)
    level = LEVELS[language].get(alert.get("risk_level", "LOW"), alert.get("risk_level", "LOW"))
    return ALERT_TEMPLATES[language].format(
        level=level,
        location=alert.get("location_name", "Unknown location"),
        risk=alert.get("risk_percent", 0),
        reason=REASON_TEMPLATES[language],
    )

def all_localized_alerts(alert: dict) -> dict:
    return {code: localized_alert(alert, code) for code in LANGUAGES}
